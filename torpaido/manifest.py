"""The compiled folder's manifest, ``compiled.yaml``: what is in the folder and what the artifact takes and gives.

A deployment runtime reads THIS file for the tensor names, dtypes and shapes, and ``class_names.json``
beside it for the labels — no key is agreed by convention. The folder stands on its own: the manifest
names the package it was compiled from as provenance (its path and the digest of its package file), and
reads nothing from it.
"""

import os
from pathlib import Path
from typing import Any, Dict, Optional, Union

import yaml

__all__ = ["COMPILED_FILE", "COMPILED_FORMAT", "PARITY_FILE", "header", "read_compiled", "write_compiled"]

#: The file that makes a folder a compiled package.
COMPILED_FILE = "compiled.yaml"
#: The parity report beside it.
PARITY_FILE = "parity.yaml"
#: The layout :func:`read_compiled`'s readers understand. Bumped when a field changes meaning.
COMPILED_FORMAT = 1


def _absolute(path: Union[str, Path]) -> Path:
    return Path(os.path.normpath(os.path.abspath(os.path.expanduser(os.path.expandvars(str(path))))))


def read_compiled(path: Union[str, Path]) -> Dict[str, Any]:
    """The manifest of the compiled folder at ``path``, as plain data.

    Raises:
        ValueError: ``path`` is not a folder holding :data:`COMPILED_FILE`, naming what is missing.
    """
    root = _absolute(path)
    if not root.is_dir():
        raise ValueError(f"no compiled package at {root}")
    manifest = root / COMPILED_FILE
    if not manifest.is_file():
        raise ValueError(f"no compiled package at {root}: {COMPILED_FILE} is missing")
    info = yaml.safe_load(manifest.read_text())
    if not isinstance(info, dict):
        raise ValueError(f"{manifest} is not a compiled package's manifest: it holds no mapping")
    return info


def header(command: Optional[str]) -> str:
    """The generated-file header of a manifest: what wrote it and how to write it again."""
    how = command or "CompilePackage(...).run() — called from Python, so no command line to repeat"
    rule = "# " + "=" * 73
    return (
        f"{rule}\n"
        "# AUTO-GENERATED FILE — DO NOT EDIT BY HAND\n"
        f"# Generated by: {how}\n"
        "# Source: torpaido/compile.py (CompilePackage)\n"
        f"# To regenerate: {how}   (it replaces this compiled folder)\n"
        f"{rule}\n"
    )


def write_compiled(folder: Path, info: Dict[str, Any]) -> Path:
    """Write ``info`` as the folder's manifest, under the generator header; returns the file."""
    path = Path(folder) / COMPILED_FILE
    path.write_text(header(info.get("command")) + yaml.safe_dump(info, sort_keys=False, allow_unicode=True))
    return path
