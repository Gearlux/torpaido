"""CompilePackage writes a STANDALONE compiled folder; CompiledPackage runs it as one op, like the package op."""

import shutil
from pathlib import Path
from typing import Any, Dict, List

import confluid
import numpy as np
import pytest
import yaml
from matrainer.artifacts import CLASS_NAMES_FILE
from matrainer.model_package import PACKAGE_FILE, ModelPackage
from matrainer.tracking.provenance import file_digest
from recordstream import Image, Label, Record
from toy_graph import sample_record

from torpaido.compile import CompilePackage
from torpaido.compiled import CompiledPackage
from torpaido.manifest import COMPILED_FILE, COMPILED_FORMAT, PARITY_FILE, read_compiled


def _compile(package: Path, samples: List[Record], **settings: Any) -> Path:
    return Path(CompilePackage(package=str(package), name="ts", samples=samples, **settings).run())


def test_compiling_writes_a_standalone_folder_with_the_manifest(package: Path, samples: List[Record]) -> None:
    out = _compile(package, samples, description="the toy classifier, scripted")

    assert out == package / "compiled" / "ts"
    assert sorted(p.name for p in out.iterdir()) == [CLASS_NAMES_FILE, COMPILED_FILE, "model.pt", PARITY_FILE]
    info = read_compiled(out)
    assert info["format"] == COMPILED_FORMAT
    assert info["backend"] == "torchscript"
    assert info["description"] == "the toy classifier, scripted"
    assert info["source"] == {
        "package": str(package),
        "package_sha256": file_digest(package / PACKAGE_FILE),
        "graph": "graphs/cfg/model.yaml",
    }
    assert info["files"] == [{"path": "model.pt", "sha256": file_digest(out / "model.pt")}]
    assert info["class_names"] == CLASS_NAMES_FILE
    assert info["inputs"] == {
        "image.data": {
            "entry": "image",
            "part": "data",
            "dtype": "uint8",
            "shape": [None, None, 3],
            "item": "recordstream.items.Image",
        }
    }
    assert info["outputs"] == {
        "scores.data": {"entry": "scores", "part": "data", "dtype": "float32", "shape": [2], "item": "numpy.ndarray"},
        "label.value": {
            "entry": "label",
            "part": "value",
            "dtype": "int64",
            "shape": [],
            "item": "recordstream.items.Label",
        },
    }
    assert info["specialized"] == {"gain.value": 2.0, "image.layout": "HWC"}
    assert info["constants"] == {"label.classes": None}
    assert info["pruned"] == ["level", "stamp", "done"]
    assert info["parity"] == {"records": 2, "status": "passed", "report": PARITY_FILE}
    assert {"torch", "torpaido", "recordstream", "matrainer"} <= set(info["packages"])


def test_the_manifest_carries_the_generator_header(package: Path, samples: List[Record]) -> None:
    out = _compile(package, samples)
    head = (out / COMPILED_FILE).read_text().splitlines()[:6]

    assert head[1] == "# AUTO-GENERATED FILE — DO NOT EDIT BY HAND"
    assert head[2].startswith("# Generated by: ")
    assert head[3] == "# Source: torpaido/compile.py (CompilePackage)"
    assert head[4].startswith("# To regenerate: ")


def test_the_envelope_lets_a_dimension_vary(package: Path, samples: List[Record]) -> None:
    out = _compile(package, samples, envelope={"image.data": "varies"})
    info = read_compiled(out)

    assert info["inputs"]["image.data"]["shape"] == [None, None, None]  # `varies`: every dimension
    assert info["envelope"] == {"image.data": "varies"}
    record = sample_record(9, 2, fill=120)
    expected = ModelPackage(path=str(package))(record)
    assert expected is not None
    assert np.allclose(CompiledPackage(path=str(out))(record)["scores"], expected["scores"])


def test_the_config_shape_is_a_runnable(package: Path) -> None:
    config = f"""\
runnable: !class:torpaido.CompilePackage
  package: {package}
  name: scripted
  backend: !class:torpaido.backends.TorchScript {{}}
  outputs: [scores, label]
  envelope: {{image.data: varies}}
  samples: !class:toy_graph.ToySamples {{}}
"""
    runnable = confluid.load(config)["runnable"]

    out = Path(runnable.run())

    assert out == package / "compiled" / "scripted"
    assert read_compiled(out)["outputs"].keys() == {"scores.data", "label.value"}


def test_the_compiled_folder_runs_on_its_own_after_the_package_is_gone(
    package: Path, samples: List[Record], tmp_path: Path
) -> None:
    out = _compile(package, samples)
    record = sample_record(4, 6, fill=77)
    expected = ModelPackage(path=str(package))(record)
    assert expected is not None
    moved = tmp_path / "shipped"
    shutil.move(str(out), str(moved))
    shutil.rmtree(package)

    answer = CompiledPackage(path=str(moved))(record)

    assert set(answer) == {"image", "gain", "tag", "scores", "label"}
    assert np.allclose(answer["scores"], expected["scores"], atol=1e-6)
    assert answer["label"] == expected["label"] and isinstance(answer["label"], Label)
    assert answer["image"] is record["image"] and answer["tag"] == "a capture"
    assert (moved / CLASS_NAMES_FILE).is_file()


def test_the_op_declares_what_it_consumes_and_produces_from_the_manifest(package: Path, samples: List[Record]) -> None:
    out = _compile(package, samples)
    op = CompiledPackage(path=str(out))

    assert op.consumes == (Image, float)
    assert op.produces == (np.ndarray, Label)


def test_a_record_outside_the_envelope_is_refused_naming_the_part_and_both_values(
    package: Path, samples: List[Record]
) -> None:
    out = _compile(package, samples)

    with pytest.raises(ValueError) as refused:
        CompiledPackage(path=str(out))(sample_record(gain=3.0))
    assert str(refused.value) == (
        f"CompiledPackage: {out} was compiled for gain.value = 2.0, and this record has 3.0 — "
        "compile with the envelope letting it vary (gain.value: varies) to run such records"
    )


def test_a_record_of_another_dtype_or_rank_is_refused(package: Path, samples: List[Record]) -> None:
    out = _compile(package, samples)
    record = sample_record()
    record["image"] = Image(np.asarray(record["image"], dtype=np.float32))

    with pytest.raises(ValueError, match="image.data is float32, and the compiled package takes uint8"):
        CompiledPackage(path=str(out))(record)


def test_a_record_missing_an_input_is_refused_naming_it(package: Path, samples: List[Record]) -> None:
    out = _compile(package, samples)

    with pytest.raises(ValueError, match=r"the record has no entry 'image' \(it has: gain, tag\)"):
        CompiledPackage(path=str(out))({"gain": 2.0, "tag": "t"})


def test_a_fixed_size_artifact_refuses_a_picture_of_another_size(package: Path, samples: List[Record]) -> None:
    out = _compile(package, [samples[0]])

    with pytest.raises(
        ValueError, match=r"image.data has shape \(3, 7, 3\), and the compiled package takes \[4, 6, 3\]"
    ):
        CompiledPackage(path=str(out))(sample_record(3, 7))


def test_compiling_again_replaces_the_folder(package: Path, samples: List[Record]) -> None:
    out = _compile(package, samples)
    (out / "stale.txt").write_text("left over")

    _compile(package, samples)

    assert not (out / "stale.txt").exists() and (out / "model.pt").is_file()


def test_a_folder_that_is_not_a_compiled_package_is_never_written_into(
    package: Path, samples: List[Record], tmp_path: Path
) -> None:
    out = tmp_path / "runs"
    out.mkdir()
    (out / "checkpoint.pth").write_bytes(b"precious")

    with pytest.raises(ValueError, match=f"CompilePackage: {out} holds files and is not a compiled package"):
        _compile(package, samples, output_dir=str(out))
    assert sorted(p.name for p in out.iterdir()) == ["checkpoint.pth"]


def test_the_output_dir_may_be_elsewhere(package: Path, samples: List[Record], tmp_path: Path) -> None:
    out = _compile(package, samples, output_dir=str(tmp_path / "elsewhere"))

    assert out == tmp_path / "elsewhere" and (out / COMPILED_FILE).is_file()


@pytest.mark.parametrize(
    "settings, message",
    [
        ({"package": ""}, "CompilePackage: 'package' is blank"),
        ({"package": "nowhere"}, "CompilePackage: no package at"),
        ({"samples": None}, "CompilePackage: 'samples' is not set — name a source of records"),
        ({"samples": []}, "CompilePackage: 'samples' yielded no record"),
        ({"name": ""}, "CompilePackage: 'name' is blank"),
    ],
)
def test_a_missing_setting_is_refused_naming_it(
    settings: Dict[str, Any], message: str, package: Path, samples: List[Record]
) -> None:
    given: Dict[str, Any] = {"package": str(package), "name": "ts", "samples": samples, **settings}
    with pytest.raises(ValueError, match=message):
        CompilePackage(**given).run()
    assert not (package / "compiled").exists()


def test_constructing_the_ops_reads_nothing(tmp_path: Path) -> None:
    assert CompiledPackage(path=str(tmp_path / "nowhere"))._runner is None
    assert CompilePackage(package=str(tmp_path / "nowhere")).package.endswith("nowhere")


@pytest.mark.parametrize("path", ["", "nowhere"])
def test_a_missing_compiled_package_is_refused_naming_it(path: str, tmp_path: Path) -> None:
    where = str(tmp_path / path) if path else ""
    with pytest.raises(
        ValueError, match="CompiledPackage: " + ("'path' is blank" if not path else "no compiled package at")
    ):
        CompiledPackage(path=where)(sample_record())


def test_a_compiled_package_of_another_format_is_refused(package: Path, samples: List[Record]) -> None:
    out = _compile(package, samples)
    text = (out / COMPILED_FILE).read_text().replace(f"format: {COMPILED_FORMAT}", "format: 99")
    (out / COMPILED_FILE).write_text(text)

    with pytest.raises(ValueError, match="format 99, this torpaido reads format 1"):
        CompiledPackage(path=str(out))(sample_record())


def test_the_parity_report_lists_each_record(package: Path, samples: List[Record]) -> None:
    out = _compile(package, samples)
    report = yaml.safe_load((out / PARITY_FILE).read_text())

    assert report["status"] == "passed"
    assert [row["record"] for row in report["records"]] == [1, 2]
    assert all(row["differences"] == [] for row in report["records"])
    assert report["tolerances"] == {"atol": 1e-5, "rtol": 1e-4}


def test_an_op_that_has_run_pickles_without_its_engine(package: Path, samples: List[Record]) -> None:
    import pickle

    out = _compile(package, samples)
    op = CompiledPackage(path=str(out))
    expected = op(sample_record())

    clone = pickle.loads(pickle.dumps(op))

    assert clone._runner is None
    assert np.allclose(clone(sample_record())["scores"], expected["scores"])
